from typing import Optional

from qgis.PyQt.QtCore import QCoreApplication, Qt
from qgis.PyQt.QtGui import QIcon
from qgis.PyQt.QtWidgets import QAction

from qgis.core import QgsApplication, Qgis, QgsMessageLog

from .civil_engineering_toolkit_dockwidget import CivilEngineeringToolkitDockWidget


class CivilEngineeringToolkit:
    """Implementación del plugin."""

    def __init__(self, iface):
        self.iface = iface

        self.actions = []
        self.menu = self.tr("&Civil Engineering Toolkit")

        self.dockwidget = None  # Instancia única (singleton)
        self.toolbar = self.iface.addToolBar("CivilEngineeringToolkit")
        self.toolbar.setObjectName("CivilEngineeringToolkit")

        # Processing provider (se registrará en initGui)
        self.provider = None

    def tr(self, message: str) -> str:
        return QCoreApplication.translate("CivilEngineeringToolkit", message)

    def add_action(
        self,
        icon_path: str,
        text: str,
        callback,
        enabled_flag: bool = True,
        add_to_menu: bool = True,
        add_to_toolbar: bool = True,
        status_tip: Optional[str] = None,
        whats_this: Optional[str] = None,
        parent=None,
    ):
        icon = QIcon(icon_path) if icon_path else QIcon()
        action = QAction(icon, text, parent if parent else self.iface.mainWindow())
        action.triggered.connect(callback)
        action.setEnabled(enabled_flag)

        if status_tip:
            action.setStatusTip(status_tip)
        if whats_this:
            action.setWhatsThis(whats_this)

        if add_to_toolbar:
            self.toolbar.addAction(action)
        if add_to_menu:
            self.iface.addPluginToMenu(self.menu, action)

        self.actions.append(action)
        return action

    def initGui(self):
        # Acción del plugin (dock) -> así SIEMPRE aparece aunque falle Processing
        self.add_action(
            icon_path="",
            text=self.tr("Civil Engineering Toolkit"),
            callback=self.run,
            parent=self.iface.mainWindow(),
        )

        # Registrar provider de Processing (sin romper carga del plugin)
        try:
            from .processing.provider import CivilEngineeringProvider  # import diferido

            if self.provider is None:
                self.provider = CivilEngineeringProvider()
                QgsApplication.processingRegistry().addProvider(self.provider)

        except Exception as e:
            QgsMessageLog.logMessage(
                f"No se pudo registrar el provider de Processing: {e}",
                "CivilEngineeringToolkit",
                Qgis.Critical,
            )
            # El plugin sigue cargando y el dock funciona.

    def unload(self):
        # Desregistrar provider de Processing
        if self.provider is not None:
            try:
                QgsApplication.processingRegistry().removeProvider(self.provider)
            except Exception:
                pass
            self.provider = None

        # Quitar acciones
        for action in self.actions:
            self.iface.removePluginMenu(self.menu, action)
            self.iface.removeToolBarIcon(action)

        # Quitar toolbar
        try:
            del self.toolbar
        except Exception:
            pass

        # Quitar dock si existe
        if self.dockwidget is not None:
            self.iface.removeDockWidget(self.dockwidget)
            self.dockwidget.deleteLater()
            self.dockwidget = None

    def run(self):
        """Muestra el dock. Lo crea solo la primera vez."""
        if self.dockwidget is None:
            self.dockwidget = CivilEngineeringToolkitDockWidget(self.iface)
            self.iface.addDockWidget(Qt.RightDockWidgetArea, self.dockwidget)

        self.dockwidget.show()
        self.dockwidget.raise_()
