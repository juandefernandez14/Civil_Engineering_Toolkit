# -*- coding: utf-8 -*-
import os
import traceback

from qgis.PyQt.QtCore import Qt, QSettings
from qgis.PyQt.QtWidgets import (
    QDockWidget, QWidget, QVBoxLayout, QHBoxLayout,
    QPushButton, QLabel, QFileDialog, QMessageBox,
    QTreeWidget, QTreeWidgetItem
)
from qgis.core import QgsMessageLog, Qgis

TAG = "CIVIL_ENGINEERING_TOOLKIT"
SETTINGS_KEY_ROOT = "civil_engineering_toolkit/root_folder"
IGNORED_DIRS = {"__pycache__", ".git", ".svn"}


def log(msg, level=Qgis.Info):
    QgsMessageLog.logMessage(str(msg), TAG, level)


class CivilEngineeringToolkitDockWidget(QDockWidget):
    """
    Dock widget autocontenido (sin .ui).
    - Raíz por defecto: <plugin_dir>/scripts
    - Árbol por carpetas (subcarpetas ilimitadas)
    - Doble click en .py => ejecuta
    """

    def __init__(self, iface, parent=None):
        super().__init__("CivilEngineeringToolkit", parent or iface.mainWindow())
        self.iface = iface

        # ===== UI (en código) =====
        main = QWidget(self)
        self.setWidget(main)
        layout = QVBoxLayout(main)
        layout.setContentsMargins(8, 8, 8, 8)

        top = QHBoxLayout()
        layout.addLayout(top)

        self.lblRoot = QLabel("Carpeta raíz: (no seleccionada)")
        self.btnChooseRoot = QPushButton("Seleccionar carpeta raíz")
        self.btnRefresh = QPushButton("Refrescar")

        top.addWidget(self.lblRoot, 1)
        top.addWidget(self.btnChooseRoot, 0)
        top.addWidget(self.btnRefresh, 0)

        self.treeScripts = QTreeWidget()
        self.treeScripts.setHeaderLabels(["Scripts (.py)"])
        layout.addWidget(self.treeScripts, 1)

        # ===== eventos =====
        self.btnChooseRoot.clicked.connect(self.choose_root_folder)
        self.btnRefresh.clicked.connect(self.refresh_tree)
        self.treeScripts.itemDoubleClicked.connect(self.on_item_double_clicked)

        # ===== raíz scripts: interna por defecto =====
        internal = self.get_internal_scripts_root()

        # Si existe setting guardado y es válido, úsalo; si no, usa internal.
        saved = self.load_root_folder()
        self.root_folder = saved if saved else internal

        # Crear carpeta interna si no existe
        if self.root_folder == internal and not os.path.isdir(internal):
            try:
                os.makedirs(internal, exist_ok=True)
            except Exception:
                pass

        self.update_root_label()
        self.refresh_tree()

    # ---------------------------
    # Rutas / settings
    # ---------------------------
    def get_internal_scripts_root(self) -> str:
        plugin_dir = os.path.dirname(os.path.abspath(__file__))
        return os.path.join(plugin_dir, "scripts")

    def load_root_folder(self) -> str:
        s = QSettings()
        root = s.value(SETTINGS_KEY_ROOT, "", type=str) or ""
        return root if root and os.path.isdir(root) else ""

    def save_root_folder(self, root: str):
        s = QSettings()
        s.setValue(SETTINGS_KEY_ROOT, root)

    def update_root_label(self):
        if not self.root_folder:
            self.lblRoot.setText("Carpeta raíz: (no seleccionada)")
            return

        internal = self.get_internal_scripts_root()
        if os.path.abspath(self.root_folder) == os.path.abspath(internal):
            self.lblRoot.setText("Carpeta raíz: (interna) scripts/")
        else:
            self.lblRoot.setText(f"Carpeta raíz: {self.root_folder}")

    # ---------------------------
    # UI actions
    # ---------------------------
    def choose_root_folder(self):
        folder = QFileDialog.getExistingDirectory(self, "Seleccionar carpeta raíz de scripts")
        if not folder:
            return
        if not os.path.isdir(folder):
            QMessageBox.critical(self, "Error", "La ruta seleccionada no es una carpeta válida.")
            return

        self.root_folder = folder
        self.save_root_folder(folder)
        self.update_root_label()
        self.refresh_tree()

    # ---------------------------
    # Árbol
    # ---------------------------
    def refresh_tree(self):
        self.treeScripts.clear()

        if not self.root_folder or not os.path.isdir(self.root_folder):
            return

        root_item = QTreeWidgetItem([os.path.basename(self.root_folder) or self.root_folder])
        root_item.setData(0, Qt.UserRole, {"type": "folder", "path": self.root_folder})
        self.treeScripts.addTopLevelItem(root_item)

        self._populate_folder_item(root_item, self.root_folder)
        root_item.setExpanded(True)

    def _populate_folder_item(self, parent_item, folder_path):
        try:
            entries = os.listdir(folder_path)
        except Exception as e:
            log(f"No se pudo listar {folder_path}: {e}", Qgis.Warning)
            return

        subdirs, pys = [], []
        for name in entries:
            if name.startswith("."):
                continue
            full = os.path.join(folder_path, name)

            if os.path.isdir(full):
                if name in IGNORED_DIRS:
                    continue
                subdirs.append(name)
            elif os.path.isfile(full) and name.lower().endswith(".py"):
                pys.append(name)

        subdirs.sort(key=str.lower)
        pys.sort(key=str.lower)

        for d in subdirs:
            full = os.path.join(folder_path, d)
            item = QTreeWidgetItem([d])
            item.setData(0, Qt.UserRole, {"type": "folder", "path": full})
            parent_item.addChild(item)
            self._populate_folder_item(item, full)

        for fn in pys:
            full = os.path.join(folder_path, fn)
            item = QTreeWidgetItem([fn])
            item.setData(0, Qt.UserRole, {"type": "script", "path": full})
            parent_item.addChild(item)

    # ---------------------------
    # Ejecutar scripts
    # ---------------------------
    def on_item_double_clicked(self, item, column):
        data = item.data(0, Qt.UserRole) or {}

        if data.get("type") != "script":
            # Carpetas: expand/collapse
            item.setExpanded(not item.isExpanded())
            return

        path = data.get("path")
        if not path or not os.path.exists(path):
            QMessageBox.critical(self, "Error", "El script no existe.")
            return

        rel = os.path.relpath(path, self.root_folder)
        resp = QMessageBox.question(
            self,
            "Ejecutar script",
            f"¿Ejecutar?\n{rel}",
            QMessageBox.Yes | QMessageBox.No,
            QMessageBox.Yes
        )
        if resp != QMessageBox.Yes:
            return

        try:
            log(f"Ejecutando: {path}")
            self.run_script_file(path)
            log("Finalizado OK", Qgis.Success)
        except Exception as e:
            tb = traceback.format_exc()
            log(tb, Qgis.Critical)
            QMessageBox.critical(self, "Error ejecutando script", f"{e}\n\n{tb}")
            raise

    def run_script_file(self, path_script: str):
        # Namespace aislado
        ns = {"__file__": path_script, "__name__": "__main__"}
        with open(path_script, "r", encoding="utf-8") as f:
            code = f.read()
        exec(compile(code, path_script, "exec"), ns, ns)

